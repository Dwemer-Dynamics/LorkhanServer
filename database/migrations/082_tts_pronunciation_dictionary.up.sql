CREATE TABLE IF NOT EXISTS lorkhan_internal.core_tts_pronunciation (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_text character varying(120) NOT NULL,
    spoken_text character varying(240) NOT NULL,
    npc_names character varying(512) NOT NULL DEFAULT '',
    races character varying(512) NOT NULL DEFAULT '',
    oghma_tags character varying(512) NOT NULL DEFAULT '',
    is_builtin boolean NOT NULL DEFAULT false,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT core_tts_pronunciation_source_not_blank CHECK (btrim(source_text) <> ''),
    CONSTRAINT core_tts_pronunciation_spoken_not_blank CHECK (btrim(spoken_text) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS core_tts_pronunciation_unique_entry
    ON lorkhan_internal.core_tts_pronunciation (
        lower(source_text),
        md5(lower(npc_names) || E'\x1f' || lower(races) || E'\x1f' || lower(oghma_tags)),
        is_builtin
    );

